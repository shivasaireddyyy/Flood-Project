// Copies the web UI (../static) into ./www so Capacitor can bundle it into the native app.
// If FS_SERVER_URL is set (e.g. https://abc.ngrok-free.app or http://192.168.1.5:8000) it is baked into the app
// as the default server, so the app opens already connected. It can still be changed inside the app.
const fs = require("fs");
const path = require("path");
const src = path.join(__dirname, "..", "static");
const dst = path.join(__dirname, "www");
if (!fs.existsSync(path.join(src, "index.html"))) {
  console.error("Cannot find ../static/index.html. Run this from the mobile/ folder of the project.");
  process.exit(1);
}
fs.rmSync(dst, { recursive: true, force: true });
fs.cpSync(src, dst, { recursive: true });
let url = (process.env.FS_SERVER_URL || "").trim().replace(/\/+$/, "");
if (url && !/^https?:\/\//i.test(url)) url = "http://" + url;
fs.writeFileSync(
  path.join(dst, "config.js"),
  "// Generated by copy-web.js\nwindow.FS_DEFAULT_API = " + JSON.stringify(url) + ";\n"
);
console.log("Copied", src, "->", dst);
console.log("Default server in app:", url || "(none: the app will ask on first launch)");
